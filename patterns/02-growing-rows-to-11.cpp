/*
Задача 2. Напишете програма, която отпечатва следния шаблон. 
В реализацията на задачата да са включени оператори за цикли, променливи и 1 константа (максималното число). 
Не се допуска отпечатване на числата само с използване на оператори за извеждане.

1 
2 3 
3 4 5 
4 5 6 7 
5 6 7 8 9 
6 7 8 9 10 11 
5 6 7 8 9 
4 5 6 7 
3 4 5 
2 3 
1
*/

#include <iostream>

using namespace std;

int main()
{
    const int maxNumber = 11;

    for (int i = 1; i <= maxNumber / 2 + 1; i++)
    {
        for (int j = 0; j < i; j++)
        {
            cout << i + j << " ";
        }
        cout << endl;
    }

    for (int i = maxNumber / 2; i > 0; i--)
    {
        for (int j = 0; j < i; j++)
        {
            cout << i + j << " ";
        }
        cout << endl;
    }

}

