#include <iostream>

using namespace std;

int f(int n) {
    if (n == 1) return 1;
    if (n == 2) return 2;
    return f(n - 1) + f(n - 2);
}

int main()
{
    int N;
    cout << "2xN matrix" << endl << "N: ";
    cin >> N;

    cout << f(N);
}