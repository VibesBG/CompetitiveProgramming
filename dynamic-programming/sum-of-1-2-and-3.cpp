/*
Задача 4. (Упражнение 3.2 от книгата Състезателно програмиране група С (стр.47)) 
Напишете  програма, която по дадено N намира за време О(N) броя на представянията на N като 
сума от числата 1, 2 и 3 и подредбата на събираемите е от значение. ( 1 точка)
*/

#include <iostream>

using namespace std;

int f(int n) {
    if (n == 0) return 1;
    if (n == 1) return 1;
    if (n == 2) return 2;

    return f(n - 1) + f(n - 2) + f(n - 3);
}

int main()
{
    int N;
    cout << "N: ";
    cin >> N;

    cout << f(N);
}