/*
Задача 4. Представяне на десетично число с римски цифри

Свойства на римската бройна система:

Тя е непозиционна, на даден символ се съпоставя определен количествен еквивалент, независимо от позицията, която той заема в числото.

Когато по-малка стойност на цифра стои пред по-голяма, то стойността и се изважда от тази на по-голямата. В противен случай се прибавя:

XI = 10+1

IX = 10-1

Всяка цифра може да бъде следвана от произволна по-малка от нея

Може да има най-много 3 последователни цифри с еднакви стойности

Има ограничения, коя по-малка цифра може да предхожда по-голяма

1 I		30 XXX		90 XC  		400 CM

5 V		40 XL 		100 C		500 D

10 X	L 50 		200 CC		900 CM

20 XX	60 LX		300 CCC		1000 M



I,    V,    X,    L,    C,      D,       M

1,   5,   10,  50,  100,  500,  1000



Забелязваме, че някои цифри се записват по сходен начин, като разликата е в използваните цифри

Например: 2 II; 20 – XX; 200 – CCC;

Или 8 VIII, 80 LXXX, 800 DCCC



Всъщност можем да получим всяко римско число, като го „сглобим“ от знаците представляват единици, десетици, стотици и хиляди.

За целта е достатъчно да се разглеждат отдясно – наляво цифрите на десетичното число и да се преобразуват една по една в римски цифри, след което се долепят

23 -> 20 (XX )+ 3 (III) = XXIII

55 -> 50 (L) + 5 (V) = LV
*/
#include <iostream>
#include <string>

using namespace std;

void romanNumeral(int n);

int main()
{
    int n;
    cin >> n;
    romanNumeral(n);
    cout << endl;
}

void romanNumeral(int n)
{
    if (n <= 0 || n > 3999) {
        return;
    }

    string thousands[] = {"", "M", "MM", "MMM"};
    string hundreds[]  = {"", "C", "CC", "CCC", "CD", "D", "DC", "DCC", "DCCC", "CM"};
    string tens[]      = {"", "X", "XX", "XXX", "XL", "L", "LX", "LXX", "LXXX", "XC"};
    string ones[]      = {"", "I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX"};

    cout << thousands[n / 1000]
         << hundreds[(n % 1000) / 100]
         << tens[(n % 100) / 10]
         << ones[n % 10];
}