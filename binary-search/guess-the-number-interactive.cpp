/*
Задача 1. (informatika.bg) Ели и Станчо играят на следната игра. 
Станчо си намисля число между 1 и 1000, включително, а Ели се опитва да го отгатне. 
След всяко нейно предположение, Станчо ѝ казва дали е уцелила, и ако не е - дали неговото число е по-голямо или по-малко ("нагоре" или "надолу"). 
За всяко питане тя трябва да пие шотче... натурален сок, а след като познае, Станчо трябва да допие останалото в бутилката. 
Тъй като от натуралния сок на нея ѝ се замайва главата, тя се стреми да познае числото на Станчо с възможно най-малко питания. 
Помогнете на Ели да измисли стратегия, с която да постигне това.

Напишете програма (2 точки) и анализ на решение на задачата (1 точка).

Как работи алгоритъмът:

Инициализация: 
Задаваме границите на интервала left = 1 и right = 1000.

Стесняване на интервала: На всяка стъпка пресмятаме mid = left + (right - left) / 2. 
Ако Станчо отговори, че неговото число е по-голямо ("нагоре"), изключваме лявата половина и поставяме left = mid + 1. 
Ако числото му е по-малко ("надолу"), изключваме дясната половина и поставяме right = mid - 1.

Резултат: Процесът приключва, когато числото бъде отгатнато. 
Най-лошият случай изисква максимално log_2 1000 = 10 питания (и съответно 10 изпити шотчета).
*/

#include <iostream>
#include <string>

using namespace std;

int main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    int left = 1, right = 1000;
    while (left <= right) {
        int mid = left + (right - left) / 2;
        cout << mid << endl;
        string response;
        if (!(cin >> response)) break;
        if (response == "correct") {
            break;
        }
        else if (response == "up") {
            left = mid + 1;
        }
        else if (response == "down") {
            right = mid - 1;
        }
    }
    return 0;
}