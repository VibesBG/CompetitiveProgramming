/*
Задача 2. (informatika.bg) Дадено е уравнение от типа A*X^5 + B*X^4 + C*X^3 + D*X^2 + E*X + F = 0, 
където A, B, C, D, E, и F са ненулеви, цели числа, с абсолютна стойност по-малка или равна на 100. 
Намерете стойност на X, която го удовлетворява (тоест намерете някой от корените на уравнението). 
Например, възможно решение за 3*X^5 - 13*X^4 - 42*X^3 + X^2 + X + 42 = 0 би било -2.297692476.

Напишете програма (2 точки) и анализ на решение на задачата (1 точка).

Как работи алгоритъмът:

Граници: Ограниченията на коефициентите са до 100. По теоремата за граници на корените, 
интервалът [-110, 110] е напълно достатъчен, за да улови поне един корен и да осигури противоположни знаци на функцията в краищата.

Ориентация: Проверяваме знака в краищата. Ако f(left) > f(right), разменяме границите, за да сме сигурни, че функцията расте в нашия интервал (т.е. f(left) < 0 и f(right) > 0).

Търсене: Изпълняваме 100 итерации на двоично търсене. На всяка стъпка проверяваме знака на f(mid) и съответно преместваме left или right.
*/

#include <iostream>
#include <iomanip>

using namespace std;

double A, B, C, D, E, F;

double f(double x) {
    return A * x * x * x * x * x + B * x * x * x * x + C * x * x * x + D * x * x + E * x + F;
}

int main() {
    if (!(cin >> A >> B >> C >> D >> E >> F)) return 0;

    double left = -110.0, right = 110.0;

    if (f(left) > f(right)) {
        swap(left, right);
    }

    for (int iter = 0; iter < 100; ++iter) {
        double mid = left + (right - left) / 2.0;
        if (f(mid) <= 0.0) {
            left = mid;
        }
        else {
            right = mid;
        }
    }

    cout << fixed << setprecision(9) << left << "\n";
    return 0;
}