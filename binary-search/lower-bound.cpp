/*
Задача 3. (informatika.bg) Даден ви е сортиран масив с N (по-малко или равно на 1,000,000) цели числа числа с абсолютна стойност по-малка или равна на 1,000,000,000. 
Намерете индекса на най-малкия негов елемент, който е по-голям или равен на дадено цяло число X, отново по-малко или равно на 1,000,000,000 по абсолютна стойност. 
Ако такъв индекс не съществува, върнете N.

Напишете програма (2 точки) и анализ на решение на задачата (1 точка).

Как работи алгоритъмът:

Инициализация: Задаваме left = 0, right = N - 1 и променлива за отговор ans = N (стойността по подразбиране, ако такъв елемент липсва).

Търсене на граница: Проверяваме средния елемент arr[mid]:Ако arr[mid] >= X, текущият индекс е валиден кандидат.
Записваме ans = mid и продължаваме да търсим наляво (right = mid - 1), за да проверим дали няма по-преден индекс,
който също отговаря на условието.Ако arr[mid] < X, елементът е твърде малък, затова преместваме търсенето надясно: left = mid + 1.

Сложност: Времевата сложност е O(\log N). Паметта е минимална – O(1).
*/

#include <iostream>
#include <vector>

using namespace std;

int main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    int n;
    if (!(cin >> n)) return 0;

    vector<int> arr(n);
    for (int i = 0; i < n; ++i) {
        cin >> arr[i];
    }

    int x;
    cin >> x;

    int left = 0, right = n - 1;
    int ans = n;

    while (left <= right) {
        int mid = left + (right - left) / 2;
        if (arr[mid] >= x) {
            ans = mid;
            right = mid - 1;
        }
        else {
            left = mid + 1;
        }
    }

    cout << ans << "\n";

    return 0;
}